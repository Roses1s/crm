import { ApiError } from "@/shared/api/client";

/**
 * Единый текст ошибки сервера для карточки лида и её окон.
 *
 * Тексты и порядок проверок взяты из карточки без изменений: сначала
 * конфликт версий, затем ошибки полей и прав, иначе — сообщение сервера.
 * Вынесено отдельно, чтобы окно проигрыша показывало те же тексты, не
 * выпрашивая функцию у страницы.
 */
export function describe(err: unknown, fallback: string): string {
  if (err instanceof ApiError) {
    if (err.code === "lead_conflict")
      return "Другой пользователь уже изменил карточку. Ваши правки не сохранены — загрузите актуальную карточку перед продолжением.";
    if (err.status === 422)
      return "Проверьте поля: ИНН должен быть из 10 или 12 цифр с верной контрольной суммой";
    if (err.status === 403) return "Недостаточно прав для этого действия";
    return err.message;
  }
  return fallback;
}
