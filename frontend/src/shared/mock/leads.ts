export const leads: Lead[] = SEED.map((s) => ({
  id: s.id,
  name: s.name,
  inn: s.inn,
  kpp: s.kpp ?? "",
  timezone: s.tz ?? "",
  company_email: s.email ?? null,
  phone: s.phone ?? "",
  logist_email: s.contactEmail ?? null,
  logist_contact: s.contact,
  logist_phone: s.contactPhone ?? "",
  credit_limit: s.limit ?? "0",
  first_call_date: s.first ?? null,
  next_call_date: s.next ?? null,
  priority: s.priority,
  stage: s.stage,
  stage_name: stageName(s.stage),
  tags: (s.tags ?? []).map(tagById),
  assigned_to: s.owner ?? null,
  assigned_to_email: s.owner ? OWNERS[s.owner].email : undefined,
  assigned_to_name: s.owner ? OWNERS[s.owner].name : undefined,
  is_archived: Boolean(s.archived),
}));

/** Активные лиды (архив скрыт) — то, что видно на доске и в списке. */
export const activeLeads = leads.filter((l) => !l.is_archived);

export const leadById = (id: number | string | undefined): Lead =>
  leads.find((l) => String(l.id) === String(id)) ?? leads[0];
